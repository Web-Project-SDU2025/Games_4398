    /*
     * 素材本身是「掉下去 ＋ 袋底弹两下」三段，比合成那版更完整，长度也翻了一倍
     * （0.5s 对 0.34s）。一局里没几次，可以做得有分量
     *
     * 注意两种声音的<b>相对</b>响度现在是这里说了算，而不是素材文件自己的电平：
     * 加载时会各自峰值归一，原始录音差了 10dB 这件事因此不会漏到游戏里
     */

